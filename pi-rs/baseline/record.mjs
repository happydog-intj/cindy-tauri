// 录制基准：用 mock 模型驱动一个 Pi 实现（PI_BIN），把 stdout 的 RPC 记录原样写到 OUT。
// 用法：PI_BIN=<pi 或 pi-rs> OUT=原版.jsonl node record.mjs
import { spawn } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readdirSync, readFileSync } from 'node:fs';
import os from 'node:os'; import path from 'node:path'; import readline from 'node:readline';
const root = path.resolve(import.meta.dirname, '../..');
const tmp = mkdtempSync(path.join(os.tmpdir(), 'pirec-'));
const agentDir = path.join(tmp, 'agent'), sessions = path.join(tmp, 'sessions'), cwd = path.join(tmp, 'work');
for (const d of [agentDir, sessions, cwd]) mkdirSync(d, { recursive: true });
const API = process.env.API || 'openai-completions';
const mock = spawn(process.execPath, [API === 'anthropic-messages' ? path.join(import.meta.dirname, 'mock-anthropic.mjs') : root + '/scripts/mock-openai.mjs'], { stdio: ['ignore', 'pipe', 'ignore'], env: process.env });
const port = await new Promise(r => readline.createInterface({ input: mock.stdout }).once('line', l => r(JSON.parse(l).port)));
writeFileSync(path.join(agentDir, 'models.json'), JSON.stringify({ providers: { smoke: { baseUrl: `http://127.0.0.1:${port}`, api: API, apiKey: 'sk-none', models: [{ id: 'mock-model', name: 'Mock' }] } } }));
const child = spawn(process.env.PI_BIN, ['--mode', 'rpc', '--no-extensions', '--no-skills', '--no-context-files', '--no-prompt-templates', '--session-dir', sessions, '--provider', 'smoke', '--model', 'mock-model'],
  { cwd, env: { ...process.env, PI_CODING_AGENT_DIR: agentDir, PI_OFFLINE: '1' }, stdio: ['pipe', 'pipe', 'inherit'] });
const out = []; let buf = '';
child.stdout.on('data', d => { buf += d; let i; while ((i = buf.indexOf('\n')) >= 0) { out.push(buf.slice(0, i)); buf = buf.slice(i + 1); } });
const send = o => child.stdin.write(JSON.stringify(o) + '\n');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const waitFor = async (pred, ms = 30000) => { const t = Date.now(); while (Date.now() - t < ms) { if (out.some(l => pred(JSON.parse(l)))) return; await sleep(50); } throw new Error('timeout'); };
const n0 = () => out.length;
send({ id: 'a', type: 'get_state' });
send({ id: 'b', type: 'get_available_models' });
send({ id: 'c', type: 'get_commands' });
await waitFor(r => r.id === 'c');
send({ id: 'p1', type: 'prompt', message: 'hi' });
await waitFor(r => r.type === 'agent_settled');
const k = out.length;
send({ id: 'p2', type: 'prompt', message: 'MOCK_WRITE_FILE please' });
await waitFor(r => r.type === 'agent_settled' && out.length > k + 3 && out.slice(k).filter(l => JSON.parse(l).type === 'agent_settled').length >= 1);
for (const [id, type] of [['m', 'get_messages'], ['s', 'get_session_stats'], ['l', 'get_last_assistant_text'], ['st', 'get_state']]) send({ id, type });
send({ id: 'n', type: 'set_session_name', name: 'rec' });
send({ id: 'bad', type: 'set_model', provider: 'smoke', modelId: 'nope' });
await sleep(800);
child.stdin.end(); await sleep(500); child.kill(); mock.kill();
writeFileSync(process.env.OUT, out.join('\n') + '\n');
const sf = readdirSync(sessions).flatMap(d => { const p = path.join(sessions, d); try { return readdirSync(p).map(f => path.join(p, f)); } catch { return [p]; } });
console.log('records', out.length, 'session files', sf);
if (sf[0]) writeFileSync(process.env.OUT.replace(/\.jsonl$/, '.session.jsonl'), readFileSync(sf[0]));
console.log('workdir files', readdirSync(cwd));
